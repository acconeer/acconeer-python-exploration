import argparse
import re
import sys
from pathlib import Path
from urllib.parse import unquote, urldefrag


DESCRIPTION = """
Validate HTML redirect pages against the built HTML docs.

Each redirect page under e.g. 'docs/datasheet' (searched recursively) is a JS
redirect (a 'window.location.replace(...)' call) that points at an
auto-generated anchor on another page. Those anchors are generated by Sphinx
from section headings, so renaming/moving a heading silently breaks the
redirect. This script catches that by verifying, against the built HTML, that
every redirect target file *and* anchor actually exists.
"""

# Matches: <script>window.location.replace("../foo/bar.html#anchor");</script>
_JS_REDIRECT_RE = re.compile(
    r"""window\.location\.replace\(\s*["']([^"']+)["']\s*\)""",
    re.IGNORECASE,
)


def extract_redirect_target(rst_text: str) -> "str | None":
    """Return the redirect URL (incl. fragment) of a JS redirect page, or None."""
    match = _JS_REDIRECT_RE.search(rst_text)
    return match.group(1).strip() if match else None


def anchor_exists(html_text: str, anchor: str) -> bool:
    """Whether an element with id=<anchor> is present in the HTML."""
    return re.search(rf"""id=["']{re.escape(anchor)}["']""", html_text) is not None


def check_redirect(source_rst: Path, build_dir: Path, docs_root: Path) -> "list[str]":
    """Validate a single redirect page. Return a list of human-readable error strings."""
    errors: list[str] = []

    target = extract_redirect_target(source_rst.read_text(encoding="utf-8"))
    if target is None:
        # Not a redirect page; nothing to validate.
        return errors

    # The built counterpart mirrors the source tree under the docs root, at any depth, e.g.
    # docs/datasheet/a212/rlg.rst -> <build_dir>/datasheet/a212/rlg.html
    built_page = build_dir / source_rst.relative_to(docs_root).with_suffix(".html")
    if not built_page.exists():
        errors.append(f"redirect page not found in build: {built_page}")
        return errors

    target_url, fragment = urldefrag(target)
    fragment = unquote(fragment)

    # Resolve the target relative to the built redirect page's location.
    target_file = (built_page.parent / target_url).resolve()
    if not target_file.exists():
        errors.append(f"target file does not exist: {target} -> {target_file}")
        return errors

    if fragment and not anchor_exists(target_file.read_text(encoding="utf-8"), fragment):
        errors.append(f"anchor '#{fragment}' not found in {target_url}")

    return errors


def main() -> None:
    parser = argparse.ArgumentParser(description=DESCRIPTION)
    parser.add_argument(
        "build_dir",
        type=Path,
        nargs="?",
        default=Path("docs/_build/html"),
        help="Path to the built HTML docs directory (default: docs/_build/html).",
    )
    parser.add_argument(
        "--source-dir",
        type=Path,
        default=Path("docs/datasheet"),
        help="Directory holding the redirect .rst pages (default: docs/datasheet).",
    )
    args = parser.parse_args()

    if not args.build_dir.is_dir():
        print(
            f"Build directory '{args.build_dir}' not found. "
            "Build the HTML docs first, e.g. 'uvx hatch run docs:html'."
        )
        sys.exit(1)

    if not args.source_dir.is_dir():
        print(f"Source directory '{args.source_dir}' not found.")
        sys.exit(1)

    docs_root = args.source_dir.parent
    redirect_pages = sorted(args.source_dir.rglob("*.rst"))

    failures = 0
    checked = 0
    for source_rst in redirect_pages:
        if extract_redirect_target(source_rst.read_text(encoding="utf-8")) is None:
            continue  # Not a redirect page.

        checked += 1
        errors = check_redirect(source_rst, args.build_dir, docs_root)
        if errors:
            failures += 1
            print(f"FAIL {source_rst}:")
            for error in errors:
                print(f"  - {error}")
        else:
            print(f"OK   {source_rst}")

    if checked == 0:
        print(f"No redirect pages found in '{args.source_dir}'.")

    if failures:
        print(f"\n{failures} of {checked} redirect page(s) are broken.")
        sys.exit(1)

    print(f"\nAll {checked} {args.source_dir} redirects point at existing targets and anchors.")
    sys.exit(0)


if __name__ == "__main__":
    main()
